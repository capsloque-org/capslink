/**
 * Detect social platform from URL
 */
export function detectPlatform(url, title = "") {
    if (!url && !title) return SOCIAL_PLATFORMS.find((p) => p.id === "website");

    // First try URL pattern matching
    if (url) {
        for (const platform of SOCIAL_PLATFORMS) {
            if (platform.pattern && platform.pattern.test(url)) {
                return platform;
            }
        }
    }

    // Fallback: match by link title (e.g. title "Facebook" → facebook platform)
    if (title) {
        const lowerTitle = title.toLowerCase().trim();
        for (const platform of SOCIAL_PLATFORMS) {
            if (platform.id !== "website" && (
                lowerTitle === platform.id ||
                lowerTitle === platform.name.toLowerCase() ||
                lowerTitle.includes(platform.id)
            )) {
                return platform;
            }
        }
    }

    return SOCIAL_PLATFORMS.find((p) => p.id === "website");
}

